from pathlib import Path
from playwright.sync_api import sync_playwright
import json,re
ROOT=Path(__file__).resolve().parents[1]; records=ROOT/'records';records.mkdir(exist_ok=True)
data=json.loads((ROOT/'data/math.json').read_text());deps=json.loads((ROOT/'data/dependencies.json').read_text())
checks=[];errors=[];external=[];console=[]
def check(name,test): checks.append({'name':name,'passed':bool(test)})
with sync_playwright() as p:
 b=p.chromium.launch(headless=True,args=['--no-sandbox']);ctx=b.new_context(viewport={'width':1440,'height':1000},offline=True);page=ctx.new_page();page.set_default_timeout(7000)
 page.on('pageerror',lambda e: errors.append(str(e)))
 page.on('console',lambda m:console.append(m.text) if m.type=='error' else None)
 page.on('request',lambda r:external.append(r.url) if r.url.startswith('http') else None)
 url=(ROOT/'web/index.html').as_uri()
 page.goto(url);page.wait_for_function('Boolean(window.proofReader)')
 live=page.evaluate('window.proofReader.statistics')
 expected_checks=json.loads((ROOT/'data/checks.json').read_text())
 check('去重统计一致',live['total']==len(deps))
 check('引用次数统计一致',live['occurrences']==len(data['reference_occurrences']))
 check('实际轮数统计一致',live['rounds']==sum(len(c['rounds']) for c in expected_checks))
 check('离线file协议加载',page.locator('.katex').count()>0)
 check('初始批注隐藏',not page.locator('#drawer').is_visible())
 check('初始无默认展开详情',page.locator('details[open]').count()==0)
 check('独立证明目标',page.locator('#target').count()==1)
 check('总标题公式渲染',page.locator('h1 .katex').count()==1)
 page.screenshot(path=str(records/'preview-desktop.png'))
 for index,ch in enumerate(data['chapters']):
  page.goto(url+'#proof/'+ch['id']);page.wait_for_timeout(120)
  check('章节 '+ch['title'],page.locator('#'+ch['id']).count()==1)
  check('公式无错误 '+ch['id'],page.locator('.katex-error').count()==0)
  check('正文横向宽度 '+ch['id'],page.evaluate('document.documentElement.scrollWidth<=innerWidth+1'))
  if index>0: check('后续章不重复总标题 '+ch['id'],data['title'].replace('$\\eta$','η') not in page.locator('#main').inner_text())
  content=page.locator('.proof-content').evaluate("el=>{const w=document.createTreeWalker(el,NodeFilter.SHOW_TEXT);let t='',n;while(n=w.nextNode())if(!n.parentElement.closest('.katex,.ref-link'))t+=n.textContent;return t;}")
  check('正文不含工程审查词 '+ch['id'],not re.search(r'EXT-\d|STEP-\d|INT-\d|本 demo|Reasoner|Judger|Checker|Maker|核查|审查|MainPaper/|&#x20;|\*\*|`',content))
  if index==1: page.screenshot(path=str(records/'preview-middle.png'))
  if index==2:
   page.locator('#conclusion').scroll_into_view_if_needed();page.screenshot(path=str(records/'preview-conclusion.png'))
 page.goto(url+'#proof/chapter-1');page.get_by_role('button',name='下一章 →').click();page.wait_for_timeout(100)
 check('下一章导航',page.locator('#chapter-2').count()==1)
 page.get_by_role('button',name='← 上一章').click();page.wait_for_timeout(100)
 check('上一章导航',page.locator('#chapter-1').count()==1)
 for occ in data['reference_occurrences']:
  page.goto(url+'#proof/'+occ['id']);page.wait_for_timeout(100);trigger=page.locator('#'+occ['id']);trigger.scroll_into_view_if_needed();before=page.evaluate('scrollY');trigger.click();page.wait_for_timeout(120)
  check('批注开启 '+occ['id'],page.locator('#drawer').is_visible())
  check('批注四块 '+occ['id'],page.locator('.annotation-section').count()==4)
  check('证据默认折叠 '+occ['id'],page.locator('#drawer details[open]').count()==0)
  check('批注公式 '+occ['id'],page.locator('#drawer .katex-error').count()==0)
  key=page.locator('.annotation-section').nth(1).bounding_box()
  check('原因首屏可见 '+occ['id'],key and key['y']+key['height']<1000)
  if occ['dependency_id']=='EXT-002': page.screenshot(path=str(records/'preview-annotation.png'))
  for selector in ['#source-details','#lean-details','#round-details']:
   page.locator(selector+' > summary').click();check('详情可展开 '+occ['id']+selector,page.locator(selector).get_attribute('open') is not None)
  check('每轮记录默认折叠 '+occ['id'],page.locator('.round-record[open]').count()==0)
  check('轮次详情数量 '+occ['id'],page.locator('.round-record').count()==len(next(c for c in expected_checks if c['dependency_id']==occ['dependency_id'])['rounds']))
  page.locator('.round-record > summary').first.click();check('逐轮可展开 '+occ['id'],page.locator('.round-record[open]').count()==1)
  page.locator('#close-drawer').click();page.wait_for_timeout(120)
  check('关闭回原位 '+occ['id'],abs(page.evaluate('scrollY')-before)<3)
  check('关闭回原焦点 '+occ['id'],trigger.evaluate('el=>document.activeElement===el'))
 page.goto(url+'#references');page.wait_for_timeout(100)
 check('引用数一致',page.locator('.reference-row').count()==len(deps))
 page.screenshot(path=str(records/'preview-references.png'))
 page.locator('#reference-search').fill('EXT-002');check('按稳定编号搜索',page.locator('.reference-row').count()==1)
 page.locator('#reference-search').fill('无匹配关键词987');check('无匹配搜索',page.locator('.reference-row').count()==0)
 page.locator('#reference-search').fill('')
 for state in ['通过','未找到','未通过','核查未完成']:
  page.locator('#status-filter').select_option(label=state)
  expected=sum(x['semantic_status']==state for x in json.loads((ROOT/'data/checks.json').read_text()))
  check('状态筛选 '+state,page.locator('.reference-row').count()==expected)
 page.locator('#status-filter').select_option('')
 categories={x['category'] for x in deps}
 for cat in categories:
  page.locator('#category-filter').select_option(label=cat);check('类别筛选 '+cat,page.locator('.reference-row').count()==sum(x['category']==cat for x in deps))
 page.locator('#category-filter').select_option('');page.locator('.reference-usage a').first.click();page.wait_for_timeout(100)
 check('引用返回正文原句',page.locator('.proof-content').count()==1)
 page.goto(url+'#review');check('数学审查入口','数学审查' in page.locator('#main').inner_text())
 for width in [390,360]:
  page.set_viewport_size({'width':width,'height':844});page.goto(url+'#proof/chapter-1');page.wait_for_timeout(100)
  check('手机无整页溢出 '+str(width),page.evaluate('document.documentElement.scrollWidth<=innerWidth+1'))
  check('手机目录可折叠 '+str(width),page.locator('#toggle-toc').is_visible())
  if width==390:page.screenshot(path=str(records/'preview-mobile.png'))
  for occ in data['reference_occurrences']:
   page.goto(url+'#proof/'+occ['id']);page.wait_for_timeout(70);trigger=page.locator('#'+occ['id']);trigger.scroll_into_view_if_needed();before=page.evaluate('scrollY');trigger.click();page.wait_for_timeout(100)
   check('手机批注开启 '+str(width)+occ['id'],page.locator('#drawer').is_visible())
   key=page.locator('.annotation-section').nth(1).bounding_box();check('手机原因首屏 '+str(width)+occ['id'],key and key['y']+key['height']<844)
   check('手机批注无整页溢出 '+str(width)+occ['id'],page.evaluate('document.documentElement.scrollWidth<=innerWidth+1'))
   if width==390 and occ['dependency_id']=='EXT-002': page.screenshot(path=str(records/'preview-mobile-annotation.png'))
   page.keyboard.press('Escape');page.wait_for_timeout(100);check('手机恢复滚动 '+str(width)+occ['id'],abs(page.evaluate('scrollY')-before)<3)
 check('无JavaScript异常',not errors);check('无控制台错误',not console);check('无网络请求',not external)
 result={'checks':checks,'passed':sum(x['passed'] for x in checks),'total':len(checks),'errors':errors,'console_errors':console,'external_requests':external,'browser':b.version,'viewports':['1440x1000','390x844','360x844'],'offline_file_protocol':True}
 (records/'browser-validation.json').write_text(json.dumps(result,ensure_ascii=False,indent=2));print(json.dumps({k:v for k,v in result.items() if k!='checks'},ensure_ascii=False));print('FAILURES',json.dumps([c for c in checks if not c['passed']],ensure_ascii=False))
 b.close()
